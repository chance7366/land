export function buildLegalCounselUserPrompt(args: {
  contextText: string;
  userQuery: string;
  history?: { role: string; content: string }[];
}): string {
  const historyBlock =
    args.history && args.history.length > 0
      ? args.history
          .slice(-6)
          .map((h) => `${h.role === "user" ? "사용자" : "자문관"}: ${h.content}`)
          .join("\n\n")
      : "(없음)";

  return `[검색된 참조 데이터베이스 (Retrieved Context)]
${args.contextText || "(법령 API 검색 결과 없음 — 단정하지 말고 추가 확인 서류를 안내하십시오.)"}

==================================================
[최근 대화]
${historyBlock}

==================================================
[사용자 질의]
${args.userQuery}

[작성 지침]
상기 참조 데이터베이스를 바탕으로 시스템 지침의 5단 구조로 답변하십시오.
■ [요약 답변]은 서술형 문단으로 핵심만 10줄 이내로 쓰십시오. 불릿·번호 목록·조문 나열 금지.
확정할 수 없는 사항은 추측하지 말고, 등기사항전부증명서·건축물대장·매각물건명세서 등 추가 확인 서류를 안내하십시오.
관리자가 찬스상담소에 붙여 넣을 수 있도록 고객 상담 멘트를 포함하십시오.`;
}

